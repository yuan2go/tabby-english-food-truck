import { createRequire } from 'node:module';
import { mkdirSync, writeFileSync } from 'node:fs';
const require = createRequire(new URL('../../../package.json', import.meta.url));
const { chromium, expect } = require('@playwright/test');
const [url, expectedSha, output] = process.argv.slice(2);
if (!url || !expectedSha || !output) throw Error('url sha output required');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, proxy: { server: 'http://127.0.0.1:1082' }, ignoreDefaultArgs: ['--mute-audio'] });
const context = await browser.newContext({ viewport: { width: 393, height: 665 }, hasTouch: true, isMobile: true });
const page = await context.newPage();
const errors = [], failedResources = [], audio = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', response => {
  const path = new URL(response.url()).pathname;
  if (response.status() >= 400 && /\.(js|css|png|jpg|webp|wav|svg)$/.test(path)) failedResources.push({ path, status: response.status() });
  if (path.endsWith('.wav')) audio.push({ path, status: response.status() });
});
const snapshot = () => page.evaluate(() => JSON.parse(localStorage.getItem('tabby.foodtruck.save.m2') ?? '{}'));
const result = { url, expectedSha, authenticated: false, freshContext: true, vpnProxy: '127.0.0.1:1082', startedAt: new Date().toISOString(), status: 'PENDING' };
try {
  result.initialCookieCount = (await context.cookies()).length;
  const response = await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
  result.httpStatus = response.status();
  await expect(page.getByRole('button', { name: '正在准备 · 晨光开门', exact: true })).toBeVisible({ timeout: 60000 });
  const shell = page.locator('[data-build-sha]');
  result.actualSha = await shell.getAttribute('data-build-sha');
  result.buildDirty = await shell.getAttribute('data-build-dirty');
  result.contentVersion = await shell.getAttribute('data-content-version');
  expect(result.actualSha).toBe(expectedSha);
  expect(result.buildDirty).toBe('false');
  await page.getByRole('button', { name: '正在准备 · 晨光开门', exact: true }).tap();
  await page.getByRole('button', { name: '先帮兔兔', exact: true }).tap();
  const before = await snapshot();
  expect(before.items).toHaveLength(0);
  expect(before.attempts).toHaveLength(0);
  await page.getByRole('button', { name: '重听兔兔：Can I have an apple, please?', exact: true }).tap();
  await expect.poll(async () => (await snapshot()).orders.find(o => o.visitor === 'rabbit')?.heard, { timeout: 18000 }).toBe(true);
  result.completedSpeech = (await snapshot()).audio.filter(a => a.status === 'completed').map(a => ({ id: a.id, status: a.status }));
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.screenshot({ path: `${output}/latest-online-request.png` });
  await page.setViewportSize({ width: 393, height: 665 });
  await page.getByRole('button', { name: '拿起香蕉', exact: true }).tap();
  await page.getByRole('button', { name: '交给兔兔', exact: true }).tap();
  expect((await snapshot()).items.some(i => i.product === 'banana' && i.location.startsWith('hand:'))).toBe(true);
  await page.getByRole('button', { name: '放回手中食品', exact: true }).tap();
  await page.getByRole('button', { name: '拿起苹果', exact: true }).tap();
  await page.getByRole('button', { name: '交给兔兔的餐盘', exact: true }).tap();
  await expect.poll(async () => (await snapshot()).adventure?.foods.some(f => f.product === 'apple' && f.place === 'guest-rabbit'), { timeout: 18000 }).toBe(true);
  await expect.poll(async () => (await snapshot()).orders.find(o => o.visitor === 'rabbit')?.status, { timeout: 18000 }).toBe('done');
  await page.getByRole('button', { name: '先帮刺刺', exact: true }).tap();
  await page.getByRole('button', { name: '拿起香蕉', exact: true }).tap();
  await page.getByRole('button', { name: '交给刺刺', exact: true }).tap();
  await expect(page.getByRole('button', { name: '一起吃早餐', exact: true })).toBeVisible({ timeout: 18000 });
  await page.getByRole('button', { name: '一起吃早餐', exact: true }).tap();
  const saved = await snapshot();
  expect(saved.adventure.rewards).toEqual(['flower-page']);
  await page.screenshot({ path: `${output}/anonymous-phone-breakfast.png` });
  await page.reload({ waitUntil: 'domcontentloaded' });
  expect((await snapshot()).adventure.foods).toEqual(saved.adventure.foods);
  expect((await snapshot()).adventure.rewards).toEqual(saved.adventure.rewards);
  await page.locator('.yard-story .entry-main').tap();
  expect((await snapshot()).adventure.chapter).toBe(1);
  const profile = await page.evaluate(() => JSON.parse(localStorage.getItem('tabby.foodtruck.profile.m2')));
  expect(profile.activityMemories.some(m => m.state.chapter === 0 && m.state.rewards.includes('flower-page'))).toBe(true);
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.screenshot({ path: `${output}/latest-online-desktop.png` });
  expect(failedResources).toEqual([]);
  expect(errors).toEqual([]);
  expect(audio.length).toBeGreaterThan(0);
  expect(audio.every(a => a.status === 200 || a.status === 206 || a.status === 304)).toBe(true);
  result.status = 'PASS';
  result.checks = ['anonymous public entry', 'exact merged-main SHA and clean build', 'complete speech playback record', 'wrong food retained', 'put back', 'actual two receipts', 'optional breakfast ending', 'reload preserves food and reward', 'desktop screenshot', 'no critical resource or page errors'];
} catch (e) {
  result.status = 'FAIL'; result.error = e.message;
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {});
  throw e;
} finally {
  result.audioResponses = audio; result.failedResources = failedResources; result.pageErrors = errors; result.finishedAt = new Date().toISOString();
  writeFileSync(`${output}/anonymous-validation.json`, JSON.stringify(result, null, 2));
  console.log(JSON.stringify({ status: result.status, sha: result.actualSha, dirty: result.buildDirty, output }));
  await browser.close();
}
